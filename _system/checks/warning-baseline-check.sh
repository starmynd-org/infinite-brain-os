#!/usr/bin/env bash
# Separate the warnings that ship in the box from the warnings you just caused.
#
# The validator's contract is its exit code and the absence of a FAILURES block. Warnings are
# deliberately not fatal, and a fresh clone prints twelve of them. README.md and START-HERE.md both
# tell a new user that "a small set of known warnings on the shipped example content" is "part of
# the box", and until now that set was promised in prose and written down nowhere. So on Day 1 the
# user sees twelve warnings, is told some of them are normal, and has no way to find out which.
# After the first edit the situation is worse, because a warning they caused is now sitting in a
# list they were taught to ignore.
#
# This check answers the question the prose could not: which of these are mine.
#
#   bash _system/checks/warning-baseline-check.sh              # run the validator, then compare
#   bash _system/checks/warning-baseline-check.sh --from FILE  # compare a validator run you already have
#   bash _system/checks/warning-baseline-check.sh --regenerate # rewrite the baseline from this tree
#
# Exit 0 when every warning is a known one. Exit 1 when a new warning appeared. A warning that is in
# the baseline and has now gone is reported too, and is not a failure: it usually means somebody
# fixed the shipped example content, and the baseline should be regenerated deliberately.
#
# Warn-only shared-check output is not part of the baseline. Those lines report live state (session
# counts, dates, whether any department carries an OPERATIONS.md yet) and change without anything
# being wrong.
#
# CAP03 / B01.
set -uo pipefail

CHECKS_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
BRAIN_ROOT=$(cd "$CHECKS_DIR/../.." && pwd)
BASELINE="$BRAIN_ROOT/_system/known-warnings.txt"

MODE=compare
SOURCE=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    --regenerate) MODE=regenerate ;;
    --from) shift; SOURCE="${1:-}" ;;
    -h|--help) sed -n '2,26p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) printf 'warning-baseline-check: unknown argument %s\n' "$1" >&2; exit 2 ;;
  esac
  shift
done

# Volatile fields are normalised so the baseline does not go stale every midnight or every time a
# count moves by one. Everything that identifies WHICH warning it is stays exact.
normalise() {
  sed -n '/^WARNINGS:/,/^All checks passed/p' \
    | grep -E '^  [A-Z]' \
    | sed -e 's/^  //' \
          -e 's/[0-9]\{4\}-[0-9]\{2\}-[0-9]\{2\}/<DATE>/g' \
          -e 's/[0-9]\{1,\} finding(s)/<N> finding(s)/' \
    | LC_ALL=C sort
}

run_validator() {
  ( cd "$BRAIN_ROOT" && bash _system/validate.sh 2>&1 )
}

RAW=$(mktemp); CURRENT=$(mktemp); KNOWN=$(mktemp)
trap 'rm -f "$RAW" "$CURRENT" "$KNOWN"' EXIT

if [ -n "$SOURCE" ]; then
  [ -f "$SOURCE" ] || { printf 'warning-baseline-check: no such file: %s\n' "$SOURCE" >&2; exit 2; }
  cat "$SOURCE" > "$RAW"
else
  run_validator > "$RAW"
fi
normalise < "$RAW" > "$CURRENT"

if [ "$MODE" = regenerate ]; then
  {
    printf '# Known warnings: the warning set that ships in the box.\n#\n'
    printf '# Generated by _system/checks/warning-baseline-check.sh --regenerate. Do not hand-edit:\n'
    printf '# a hand-typed baseline drifts from the validator and then hides a real warning.\n#\n'
    printf '# Regenerated %s on %s, bash %s.\n\n' \
      "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$(uname -s 2>/dev/null || echo unknown)" "${BASH_VERSION:-unknown}"
    cat "$CURRENT"
  } > "$BASELINE"
  printf 'regenerated\t%s\t%s known warning(s)\n' "$BASELINE" "$(wc -l < "$CURRENT" | tr -d ' ')"
  exit 0
fi

if [ ! -f "$BASELINE" ]; then
  printf 'warning-baseline: no baseline at %s; run with --regenerate on a clean checkout\n' "$BASELINE" >&2
  exit 2
fi
grep -v '^#' "$BASELINE" | grep -v '^[[:space:]]*$' | LC_ALL=C sort > "$KNOWN"

NEW=$(LC_ALL=C comm -13 "$KNOWN" "$CURRENT")
GONE=$(LC_ALL=C comm -23 "$KNOWN" "$CURRENT")
n_current=$(wc -l < "$CURRENT" | tr -d ' ')
n_known=$(wc -l < "$KNOWN" | tr -d ' ')
n_new=$(printf '%s' "$NEW" | grep -c . || true)
n_gone=$(printf '%s' "$GONE" | grep -c . || true)

printf 'warning-baseline: %s warning(s) now, %s in the shipped baseline.\n' "$n_current" "$n_known"

if [ "$n_gone" -gt 0 ]; then
  printf '\nGONE (in the baseline, not printed now). Not a failure: regenerate the baseline if this was deliberate.\n'
  printf '%s\n' "$GONE" | sed 's/^/  - /'
fi

if [ "$n_new" -gt 0 ]; then
  printf '\nYOURS (%s new warning(s), not part of the box):\n' "$n_new"
  printf '%s\n' "$NEW" | sed 's/^/  ! /'
  printf '\nverdict\tNEW WARNINGS\n'
  exit 1
fi

printf '\nverdict\tCLEAN (every warning printed is one that ships in the box)\n'
exit 0
